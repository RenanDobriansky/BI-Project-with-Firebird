-- ============================================================
-- 8. EXEMPLOS DE PEDIDOS COM DATA NULA OU CODIGO NULO
-- ============================================================
SELECT FIRST 30
    p.EMPRESA,
    p.ID AS ID_PEDIDO,
    p.NUMPEDIDO,
    p.DATAEMISSAO,
    p.DATAENTRADA,
    p.CLIENTE AS CODIGO_CLIENTE_ORIGEM,
    p.IDVENDEDOR,
    p.STATUS,
    p.SITUACAO,
    p.ORIGEM
FROM PEDIDO p
WHERE COALESCE(p.STATUS, '') <> 'C'
  AND COALESCE(p.SITUACAO, '') <> 'C'
  AND (
      COALESCE(p.DATAEMISSAO, p.DATAENTRADA) IS NULL
      OR COALESCE(p.NUMPEDIDO, p.ID) IS NULL
  )
ORDER BY p.ID DESC;
